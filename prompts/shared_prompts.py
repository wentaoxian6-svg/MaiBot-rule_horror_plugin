"""
共享 Prompt 工具

历史上这里曾容纳规则/场景描述/JSON 示例等 11 个 Prompt 构造函数，
但全代码库零调用点，实际 Prompt 均以 inline 形式散落在 services 层。
现仅保留 remove_emojis 工具函数；inline Prompt 现状不再通过本模块伪装"已模块化"。
"""

import re


def remove_emojis(text: str) -> str:
    """移除文本中的emoji表情符号

    Args:
        text: 输入文本

    Returns:
        移除emoji后的文本
    """
    # 合并 Unicode 区间，覆盖常见 emoji 区块（含历史保留的非 emoji 区段）
    emoji_pattern = re.compile(
        "["
        "\U00002000-\U0000206F"  # 通用标点（历史保留）
        "\U000023E9-\U000023FA"  # 杂项技术符号
        "\U000024C2-\U0001F251"  # 圈起来的字母数字和表意文字（含麻将、扑克等）
        "\U000025AA-\U000025FE"  # 几何图形
        "\U00002600-\U000026FF"  # 杂项符号
        "\U00002700-\U000027BF"  # 装饰符号
        "\U00002934-\U00002935"  # 箭头
        "\U00002B05-\U00002B07"  # 杂项符号
        "\U00002B1B-\U00002B1C"  # 杂项符号
        "\U00002B50-\U00002B55"  # 星号
        "\U00003030"             # CJK 符号和标点
        "\U0000303D"             # CJK 符号和标点
        "\U00003297-\U00003299"  # 圈起来的 CJK 字母和月份
        "\U0000FE0F"             # 变体选择符-16
        "\U0001F1E0-\U0001F1FF"  # 旗帜
        "\U0001F200-\U0001F2FF"  # 圈起来的表意文字补充
        "\U0001F300-\U0001F5FF"  # 符号和象形文字
        "\U0001F600-\U0001F64F"  # 表情符号
        "\U0001F680-\U0001F6FF"  # 交通和地图符号
        "\U0001F700-\U0001F77F"  # 炼金术符号
        "\U0001F780-\U0001F7FF"  # 几何图形扩展
        "\U0001F800-\U0001F8FF"  # 补充箭头-C
        "\U0001F900-\U0001F9FF"  # 补充符号和象形文字
        "\U0001FA00-\U0001FA6F"  # 国际象棋符号
        "\U0001FA70-\U0001FAFF"  # 符号和象形文字扩展-A
        "]+",
        flags=re.UNICODE,
    )
    return emoji_pattern.sub(r"", text)
